import argparse
import json
import re
from pathlib import Path
from urllib.error import URLError
from urllib.parse import unquote, urlsplit, urlunsplit
from urllib.request import Request, urlopen

from schema_validation import validate_item_schema


PROJECT_DIRECTORY = Path(__file__).resolve().parent.parent
UPDATER_DIRECTORY = PROJECT_DIRECTORY / 'item-updater/src/main/java/org/allaymc/updater/item'
REGISTRY_PATH = UPDATER_DIRECTORY / 'ItemStateUpdaters.java'
GRADLE_PROPERTIES_PATH = PROJECT_DIRECTORY / 'gradle.properties'


def get_version(source):
    parsed = urlsplit(source)
    filename = Path(unquote(parsed.path) if parsed.scheme in ('http', 'https') else source).name
    match = re.search(
        r'_to_([0-9]+)\.([0-9]+)\.([0-9]+)'
        r'(?:\.[0-9]+)?(?:_[A-Za-z][A-Za-z0-9_-]*)?\.json$',
        filename
    )
    if not match:
        raise ValueError(
            'The schema filename must end with '
            '_to_<major>.<minor>.<patch>[.<build>][_<suffix>].json'
        )
    return tuple(int(part) for part in match.groups())


def load_schema(source):
    parsed = urlsplit(source)
    if parsed.scheme in ('http', 'https'):
        parts = parsed.path.strip('/').split('/')
        if parsed.hostname in ('github.com', 'www.github.com'):
            if len(parts) < 5 or parts[2] not in ('blob', 'raw'):
                raise ValueError('Provide a URL to a JSON file on GitHub')
            source = urlunsplit((
                'https', 'raw.githubusercontent.com',
                '/' + '/'.join(parts[:2] + parts[3:]), '', ''
            ))
        request = Request(source, headers={'User-Agent': 'StateUpdater-item-generator'})
        with urlopen(request, timeout=30) as response:
            data = json.loads(response.read().decode('utf-8-sig'))
    else:
        data = json.loads(Path(source).read_text(encoding='utf-8-sig'))

    validate_item_schema(data)
    return data


def java_string(value):
    if not isinstance(value, str):
        raise ValueError('The item identifier must be a string')
    return json.dumps(value, ensure_ascii=True)


def generate_rename_id(data, code):
    for old, new in data.get('renamedIds', {}).items():
        code.append(f'        context.renameId({java_string(old)}, {java_string(new)});')


def generate_remap_meta(data, code):
    for item, remaps in data.get('remappedMetas', {}).items():
        if not isinstance(remaps, dict):
            raise ValueError(f'Metadata remappings for {item} must be a JSON object')
        if not remaps:
            continue
        entries = []
        for old_meta, new_item in sorted(remaps.items(), key=lambda entry: int(entry[0])):
            entries.append(f'                new RemapMetaEntry({int(old_meta)}, {java_string(new_item)})')
        code.append(
            f'        context.remapMeta({java_string(item)},\n'
            + ',\n'.join(entries)
            + '\n        );'
        )


def generate_class(data, version, class_name):
    renames = []
    remaps = []
    generate_rename_id(data, renames)
    generate_remap_meta(data, remaps)

    code = [
        'package org.allaymc.updater.item;',
        '',
        'import org.allaymc.updater.item.context.ItemUpdaterContext;',
    ]
    if remaps:
        code.append('import org.allaymc.updater.item.context.RemapMetaEntry;')
    code.extend([
        '',
        '/**',
        ' * This file is automatically generated by tools/item_scheme_to_code.py.',
        ' * Do not edit this file manually.',
        ' */',
        f'public class {class_name} extends ItemStateUpdater {{',
        f'    public static final ItemStateUpdater INSTANCE = new {class_name}();',
        '',
        f'    private {class_name}() {{',
        f'        super({", ".join(str(part) for part in version)});',
        '    }',
        '',
        '    @Override',
        '    public void registerUpdaters(ItemUpdaterContext context) {',
    ])
    code.extend(renames)
    if renames and remaps:
        code.append('')
    code.extend(remaps)
    code.extend(['    }', '}', ''])
    return '\n'.join(code)


def register_updater(version, class_name):
    source = REGISTRY_PATH.read_text(encoding='utf-8-sig')
    entries = list(re.finditer(
        r'^        updaters\.add\(ItemStateUpdater_([0-9]+)_([0-9]+)_([0-9]+)\.INSTANCE\);\n',
        source, re.MULTILINE
    ))
    if not entries:
        raise ValueError('Could not find updater registrations in ItemStateUpdaters.java')

    insert_at = entries[-1].end()
    for entry in entries:
        registered_version = tuple(int(part) for part in entry.groups())
        if registered_version == version:
            return source
        if registered_version > version and insert_at == entries[-1].end():
            insert_at = entry.start()
    registration = f'        updaters.add({class_name}.INSTANCE);\n'
    return source[:insert_at] + registration + source[insert_at:]


def update_gradle_version(version):
    source = GRADLE_PROPERTIES_PATH.read_text(encoding='utf-8-sig')
    version_string = '.'.join(str(part) for part in version)
    source, replacements = re.subn(
        r'^([ \t]*item-updater\.version[ \t]*=[ \t]*)'
        r'[0-9]+\.[0-9]+\.[0-9]+(?=-|[ \t]*$)',
        lambda match: match.group(1) + version_string,
        source, flags=re.MULTILINE
    )
    if replacements != 1:
        raise ValueError(
            'Expected exactly one item-updater.version property with a '
            'major.minor.patch version in gradle.properties'
        )
    return source


def write_source(path, source):
    encoding = 'utf-8'
    newline = '\n'
    if path.exists():
        original = path.read_bytes()
        if original.startswith(b'\xef\xbb\xbf'):
            encoding = 'utf-8-sig'
        original.decode(encoding)
        if b'\r\n' in original:
            newline = '\r\n'
        if original == source.replace('\n', newline).encode(encoding):
            return
    path.write_bytes(source.replace('\n', newline).encode(encoding))


def main():
    parser = argparse.ArgumentParser(
        description='Generates and registers an ItemStateUpdater from a JSON schema and updates its Gradle version.'
    )
    parser.add_argument(
        'source', nargs='?',
        help='GitHub/raw URL or path to a schema with a version in its filename; prompts for a URL if omitted'
    )
    args = parser.parse_args()
    try:
        source = (args.source if args.source is not None else input('JSON schema URL: ')).strip()
        if not source:
            raise ValueError('Provide a schema URL')
        version = get_version(source)
        class_name = 'ItemStateUpdater_' + '_'.join(str(part) for part in version)
        class_source = generate_class(load_schema(source), version, class_name)
        registry_source = register_updater(version, class_name)
        gradle_properties_source = update_gradle_version(version)
        output_path = UPDATER_DIRECTORY / f'{class_name}.java'
        write_source(output_path, class_source)
        write_source(REGISTRY_PATH, registry_source)
        write_source(GRADLE_PROPERTIES_PATH, gradle_properties_source)
    except (OSError, URLError, ValueError, EOFError) as error:
        parser.error(str(error))
    print(f'Generated updater: {output_path}')


if __name__ == '__main__':
    main()
